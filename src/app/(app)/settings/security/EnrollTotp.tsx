"use client";

import { useState, useTransition } from "react";
import { useRouter } from "next/navigation";
import { confirmTotp, enrollTotp } from "./actions";

/** Two-factor setup: shows the QR code, then asks for the first code to confirm. */
interface Labels {
  setup: string;
  scan: string;
  key: string;
  code: string;
  confirm: string;
}

export function EnrollTotp({ labels }: { labels: Labels }) {
  const router = useRouter();
  const [pending, startTransition] = useTransition();
  const [data, setData] = useState<{ factorId: string; qr: string; secret: string } | null>(null);
  const [error, setError] = useState<string | null>(null);

  const start = () =>
    startTransition(async () => {
      setError(null);
      const r = await enrollTotp();
      if (r.ok) setData({ factorId: r.factorId, qr: r.qr, secret: r.secret });
      else setError(r.error);
    });

  const confirm = (form: HTMLFormElement) =>
    startTransition(async () => {
      setError(null);
      const code = String(new FormData(form).get("code") ?? "");
      const r = await confirmTotp(data!.factorId, code);
      if (r.ok) router.refresh();
      else setError(r.error ?? "");
    });

  if (!data) {
    return (
      <div>
        <button type="button" onClick={start} disabled={pending} className="rounded-lg bg-brand-600 px-4 py-2 text-sm font-medium text-white hover:bg-brand-700 disabled:opacity-60">
          {labels.setup}
        </button>
        {error && <p role="alert" className="mt-2 text-sm text-red-700">{error}</p>}
      </div>
    );
  }
  return (
    <div className="space-y-3">
      <p className="text-sm text-ink-soft">{labels.scan}</p>
      {/* The QR code is a data: image generated by the auth service for this account only. */}
      {/* eslint-disable-next-line @next/next/no-img-element */}
      <img src={data.qr} alt="" className="size-44 rounded-lg border border-line bg-white p-2" />
      <p className="text-xs text-muted">{labels.key} <code className="num select-all break-all rounded bg-canvas px-1.5 py-0.5 text-ink">{data.secret}</code></p>
      <form onSubmit={(e) => { e.preventDefault(); confirm(e.currentTarget); }} className="flex flex-wrap items-end gap-2">
        <label className="text-sm font-medium text-ink">
          <span className="mb-1 block">{labels.code}</span>
          <input name="code" inputMode="numeric" pattern="\d{6}" maxLength={6} autoComplete="one-time-code" required className="num w-36 rounded-lg border border-line px-3 py-2 text-center text-lg tracking-widest" />
        </label>
        <button type="submit" disabled={pending} className="rounded-lg bg-brand-600 px-4 py-2 text-sm font-medium text-white hover:bg-brand-700 disabled:opacity-60">{labels.confirm}</button>
      </form>
      {error && <p role="alert" className="text-sm text-red-700">{error}</p>}
    </div>
  );
}
