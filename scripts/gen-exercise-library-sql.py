"""Generates the exercise-library migration from supabase/data/exercise-library.json.

The JSON is the coach-provided exercise list (exported from the "Exercise Library"
PDF, one demonstration video link per exercise). The migration:
  * updates system exercises whose name matches (keeps existing cues/descriptions),
  * inserts the rest as system exercises (owner_id null),
  * archives older system exercises that are not on the list (archived, not deleted,
    so programs that reference them keep working).
"""
import json, pathlib, sys

root = pathlib.Path(__file__).resolve().parent.parent
data = json.loads((root / "supabase/data/exercise-library.json").read_text())
out_path = root / "supabase/migrations" / (sys.argv[1] if len(sys.argv) > 1 else "20261022132549_exercise_library.sql")

# Compact one-line-per-exercise rows: name|category|pattern|muscles|equipment|difficulty|video|tags|source
# Arrays are ';'-joined. Video is 'w:<id>[&t=..]' (watch) or 's:<id>' (shorts); the full URL and the
# thumbnail are derived in SQL, so nothing is stored twice.
def field(v):
    v = "" if v is None else str(v)
    assert "|" not in v and ";" not in v.replace("; ", "\0") or True
    return v

rows = []
for r in data:
    for k in ("name", "category", "movement_pattern", "difficulty"):
        assert "|" not in r[k], r[k]
    vid = r["video_url"]
    if "/shorts/" in vid:
        code = "s:" + vid.split("/shorts/")[1]
    elif "watch?v=" in vid:
        code = "w:" + vid.split("watch?v=")[1]
    else:
        code = "u:" + vid          # any other https link, kept as-is
    src = r.get("source") or ""
    assert "|" not in src
    for arr in (r["primary_muscles"], r["equipment"], r["tags"]):
        assert all(";" not in a and "|" not in a for a in arr)
    rows.append("|".join([r["name"], r["category"], r["movement_pattern"], ";".join(r["primary_muscles"]), ";".join(r["equipment"]),
                          r["difficulty"], code, ";".join(r["tags"]), src]))
payload = "\n".join(rows)
assert "$lib$" not in payload

sql = f"""-- Exercise library from the coach-provided list (generated by scripts/gen-exercise-library-sql.py).
-- Row format: name|category|pattern|muscles|equipment|difficulty|video|tags|source   (arrays ';'-joined;
-- video 'w:<id>' = youtube watch link, 's:<id>' = shorts; URL and thumbnail are derived below).
create or replace function pg_temp.exercise_key(n text) returns text language sql immutable as $$
  select regexp_replace(lower(regexp_replace(n, '[^a-zA-Z0-9]', '', 'g')), 's$', '')
$$;

create temporary table lib as
select
  split_part(l, '|', 1) as name,
  split_part(l, '|', 2) as category,
  split_part(l, '|', 3) as movement_pattern,
  string_to_array(split_part(l, '|', 4), ';') as primary_muscles,
  string_to_array(split_part(l, '|', 5), ';') as equipment,
  split_part(l, '|', 6) as difficulty,
  case left(split_part(l, '|', 7), 1)
       when 's' then 'https://www.youtube.com/shorts/' || substr(split_part(l, '|', 7), 3)
       when 'u' then substr(split_part(l, '|', 7), 3)
       else 'https://www.youtube.com/watch?v=' || substr(split_part(l, '|', 7), 3) end as video_url,
  case when split_part(l, '|', 7) like 'u:%' then null
       else 'https://i.ytimg.com/vi/' || substr(split_part(l, '|', 7), 3, 11) || '/hqdefault.jpg' end as thumbnail_url,
  nullif(split_part(l, '|', 9), '') as source,
  string_to_array(split_part(l, '|', 8), ';') as tags
from regexp_split_to_table($lib${payload}$lib$, E'\n') as l
where l <> '';

-- 1. Existing system exercises with the same name: attach the video and list metadata.
update public.exercises e
   set name = l.name, category = l.category, movement_pattern = l.movement_pattern,
       primary_muscles = case when cardinality(l.primary_muscles) > 0 and l.primary_muscles <> '{{""}}' then l.primary_muscles else e.primary_muscles end,
       equipment = l.equipment, video_url = l.video_url, thumbnail_url = l.thumbnail_url,
       tags = l.tags, archived = false,
       source = coalesce(l.source, 'Performance360 exercise library')
  from lib l
 where e.owner_id is null and pg_temp.exercise_key(e.name) = pg_temp.exercise_key(l.name);

-- 2. New exercises.
insert into public.exercises (owner_id, name, category, movement_pattern, primary_muscles, equipment, difficulty,
                              video_url, thumbnail_url, tags, source)
select null, l.name, l.category, l.movement_pattern,
       case when l.primary_muscles = '{{""}}' then '{{}}'::text[] else l.primary_muscles end,
       l.equipment, l.difficulty, l.video_url, l.thumbnail_url, l.tags,
       coalesce(l.source, 'Performance360 exercise library')
  from lib l
 where not exists (select 1 from public.exercises e
                    where e.owner_id is null and pg_temp.exercise_key(e.name) = pg_temp.exercise_key(l.name));

-- 3. Older system exercises that are not on the list are archived (history is kept).
update public.exercises e set archived = true
 where e.owner_id is null
   and not exists (select 1 from lib l where pg_temp.exercise_key(l.name) = pg_temp.exercise_key(e.name));

create index if not exists exercises_pattern_idx on public.exercises (movement_pattern);
drop table lib;
"""
out_path.write_text(sql)
print(f"wrote {out_path.relative_to(root)} ({len(data)} exercises)")
